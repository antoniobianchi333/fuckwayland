FORBIDDEN = ("save", "write", "store", "persist")


def identifiers(text: str) -> list:
    """Every C symbol a type description makes callable."""
    out = []
    for line in text.splitlines():
        i = line.find('c:identifier="')
        if i >= 0:
            out.append(line[i + 14:line.index('"', i + 14)])
    return sorted(set(out))


def gir(gen: int) -> tuple:
    """(namespace, gir text) for one mutter generation."""
    lib, ints = BUILDS[gen]
    ns = "FwOverlap%d" % gen
    tail = "".join(TAIL_FIELD.format(off=56 + 4 * i) for i in range(ints))
    text = HEAD.format(gen=gen, ns=ns, lib=lib, tail=tail) + BODY
    # the extension must not be *able* to reach Mutter's monitors.xml writer, even
    # by mistake: a symbol that is not described cannot be called from JS at all
    for sym in identifiers(text):
        for bad in FORBIDDEN:
            if bad in sym.lower():
                raise SystemExit("gen-gir: %s makes %s callable" % (ns, sym))
    return ns, text


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    here = os.path.dirname(os.path.abspath(__file__))
    outdir = args[0] if args else os.path.join(
        os.path.dirname(here), "fuckwayland-overlap@fuckwayland", "typelib")
    os.makedirs(outdir, exist_ok=True)
    bad = 0
    for gen in sorted(BUILDS):
        ns, text = gir(gen)
        gpath = os.path.join(here, "%s-1.0.gir" % ns)
        tpath = os.path.join(outdir, "%s-1.0.typelib" % ns)
        tmp = tpath + ".new" if check else tpath
        if check:
            if not os.path.exists(gpath) or open(gpath).read() != text:
                print("stale: %s" % gpath)
                bad = 1
        else:
            with open(gpath, "w") as fh:
                fh.write(text)
        subprocess.run(["g-ir-compiler", "--includedir", "/usr/share/gir-1.0",
                        "-o", tmp, gpath if check else gpath], check=True)
        if check:
            old = open(tpath, "rb").read() if os.path.exists(tpath) else b""
            new = open(tmp, "rb").read()
            os.unlink(tmp)
            if old != new:
                print("stale: %s (%s != %s)"
                      % (tpath, hashlib.sha256(old).hexdigest()[:12],
                         hashlib.sha256(new).hexdigest()[:12]))
                bad = 1
        else:
            print("%s  %s  %s" % (ns, gpath, tpath))
    return bad


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
