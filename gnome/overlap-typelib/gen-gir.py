#!/usr/bin/env python3
"""Generate (and compile) the type descriptions the overlap extension ships.

libmutter is built with hidden visibility, but the test-export macro expands to a real
export, so the four symbols the extension needs are ordinary dynamic symbols in the
shipped library -- absent from the introspection data, not from the library.  A GNOME
Shell extension can prepend its own search path and load a type description it ships
itself, which is what these files are.

Two properties of what is emitted here matter more than anything else in this tree:

**No pointer is ever declared as a pointer.**  Every pointer field in Mutter's private
structures is declared `guint64`, so reading one yields a *number* and gjs never
dereferences anything on our behalf.  Stepping from one struct to the next goes through
`g_memdup2(ptr, n)` -- a bounded copy of exactly n bytes -- and `g_strndup(ptr, n)` for
the connector strings, which lets the extension range-check the number against
`/proc/self/maps` before any address is read at all.  A wrong offset then produces
garbage or a refusal, not a SIGSEGV; with pointers declared as pointers it produced a
dead gnome-shell (measured, GNOME 50.1, docs/Technical.md section 6).

**Nothing that can write ~/.config/monitors.xml is declared.**
`meta_monitor_config_manager_save_current()` is not in the file, and neither is any
other `*save*` symbol, so no code in the extension can reach the writer even by
mistake.  `tests/test_gnome_overlap.py` asserts that about the shipped .gir and about
the shipped .typelib bytes.

The layout below is measured, not assumed (docs/Technical.md section 6): `parent_config`
and `switch_config` were proved with sentinels written through the exported accessors.
`logical_monitor_configs` is at offset 40 on both mutter 14 and mutter 18; the tail and
the total size are not the same, which is exactly why there is one description per
generation and why the extension refuses to run one against the other.

    offset  mutter 14 (GNOME 46)      mutter 18 (GNOME 50)
    0..23   GObject                   GObject
    24      parent_config             parent_config
    32      key                       key
    40      logical_monitor_configs   logical_monitor_configs
    48      disabled_monitor_specs    disabled_monitor_specs
    56      flags                     (unused)
    60      layout_mode               (unused)
    64      switch_config             (unused)
    68      padding                   layout_mode
    72      --                        switch_config
    76      --                        padding
    size    72                        80

Usage:  python3 gnome/overlap-typelib/gen-gir.py [OUTDIR]
        (OUTDIR defaults to gnome/fuckwayland-overlap@fuckwayland/typelib)

Needs `g-ir-compiler` (Ubuntu: libgirepository1.0-dev).  The compiled typelibs are
checked in because no desktop has that package installed; `--check` recompiles and
compares, which is how CI notices a .gir edited without a rebuild.
"""

